"""POST-HOC DESCRIPTIVE exposure audit over the interrupted run and its resume.

Each registered case is read from exactly one directory, the source_run recorded by
analyze_regions_validation_combined.py. Case, pair and limit semantics are the frozen
audit_treatment_exposure.py, imported unchanged; only the receipt gate and the
per-case run directory differ.
"""
from pathlib import Path
from collections import Counter
import argparse
import importlib.util
import json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module


FROZEN = HERE / 'audit_treatment_exposure.py'
frozen = load('exposure_audit_frozen', FROZEN)
combined_analysis = load('regions_validation_combined', HERE / 'analyze_regions_validation_combined.py')
read, require, sha_file = frozen.read, frozen.require, frozen.sha_file
INTERRUPTION = 'interruption-record-20261024.json'


def rooted(path):
    path = Path(path)
    return (path if path.is_absolute() else ROOT / path).resolve()


def require_stopped(prior, resume):
    """Replace the single-run gate; must run before any result or journal access."""
    receipt = read(resume / 'launch-receipt.json')
    require(receipt.get('owned_processes_stopped') is True and not receipt.get('cleanup_errors'),
            'Owned cleanup must finish without errors before reading any trace')
    require(receipt.get('purpose') == frozen.PURPOSE and receipt.get('status') in ('all_owed_cases_accounted', 'partial'),
            'A terminal resume launcher receipt is required')
    require(not (prior / 'launch-receipt.json').exists(), 'Prior run unexpectedly has a launch receipt')
    require((prior / INTERRUPTION).is_file(), 'Prior run lacks its interruption record')
    plan = read(resume / 'resume-plan.json')
    require(combined_analysis.local(plan['prior_output']).resolve() == prior, 'Resume plan names a different prior run')
    manifest = read(prior / 'manifest.json')
    for cid, digest in plan['prior_completed_result_sha256'].items():
        case = next(c for c in manifest['cases'] if c['case_id'] == cid)
        require(sha_file(prior / f"worker-{case['worker']}" / 'run/results' / f'{cid}.json') == digest,
                'Prior result changed after resume registration: ' + cid)
    return receipt, plan


def audit(prior, resume, analysis_path, output):
    prior, resume, analysis_path, output = (Path(p).resolve() for p in (prior, resume, analysis_path, output))
    require(not output.exists(), 'Never overwrite an exposure audit')
    stopped, plan = require_stopped(prior, resume)  # Must happen before any result/journal access.
    analysis, manifest = read(analysis_path), read(prior / 'manifest.json')
    require(read(resume / 'manifest.json') == manifest, 'Prior and resume manifests differ')
    require(analysis.get('status') == 'PROSPECTIVE_OFFLINE_ANALYSIS' and analysis.get('source_files_match') is True,
            'Final registered offline analysis required')
    require(rooted(analysis.get('run', '')) == prior and rooted(analysis.get('resume_run', '')) == resume
            and analysis.get('resume_plan') == plan, 'Analysis was produced for a different prior/resume split')
    require(analysis.get('combined_wrapper_sha256') == sha_file(HERE / 'analyze_regions_validation_combined.py'),
            'Combined analysis wrapper changed after analysis')
    analysis_plan = read(HERE / 'analysis-plan-v1.json')
    require(analysis.get('analysis_sha256') == analysis_plan['source_sha256']['work/id60-regions-validation/analyze_regions_validation.py'],
            'Analysis generated by unregistered frozen analyzer')
    require(analysis.get('manifest_sha256') == manifest.get('manifest_sha256') == frozen.MANIFEST, 'Wrong registered study')
    manifest_content = {k: v for k, v in manifest.items() if k != 'manifest_sha256'}
    require(frozen.sha_bytes(json.dumps(manifest_content, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()) == frozen.MANIFEST,
            'Manifest content identity mismatch')
    require(len(manifest.get('cases', [])) == 24 and len(analysis.get('cases', [])) == 24, 'Fixed 24 slots required')
    sources = {n: sha_file(ROOT / n) for n in frozen.SOURCE_NAMES}
    require(all(v == manifest['source_files'].get(n) for n, v in sources.items()), 'Frozen exposure metadata source changed')
    analyzed = {c['case_id']: c for c in analysis['cases']}
    require(set(analyzed) == {c['case_id'] for c in manifest['cases']}, 'Analysis case accounting mismatch')
    owed = set(plan['owed_case_ids'])
    for cid, row in analyzed.items():
        require(row.get('source_run') == ('resume' if cid in owed else 'prior'), 'Case source run differs from resume plan: ' + cid)
    runs = {'prior': prior, 'resume': resume}
    constants, reports, states = frozen.focus_constants(), [], {}
    for case in manifest['cases']:
        row = analyzed[case['case_id']]
        report, state = frozen.case_audit(runs[row['source_run']], case, row, constants)
        report.update(source_run=row['source_run'], reattempt_after_zero_step_kill=row.get('reattempt_after_zero_step_kill', False))
        reports.append(report)
        states[(case['seed'], case['comparison_arm'])] = state
        print(json.dumps({'case_id': case['case_id'], 'source_run': row['source_run'], 'posthoc_exposure_status': report['status']}), flush=True)
    pair_infos = {p['seed']: p for p in analysis['pairs']}
    pairs = [frozen.compare_pair(seed, states[(seed, 'point')], states[(seed, 'regions')], pair_infos[seed]) for seed in manifest['seeds']]
    result = {'status': 'POST_HOC_DESCRIPTIVE_TREATMENT_EXPOSURE_AUDIT', 'not_preregistered_primary_analysis': True,
              'source_script_sha256': sha_file(FROZEN), 'combined_wrapper_sha256': sha_file(Path(__file__)),
              'frozen_metadata_sources_sha256': sources,
              'final_analysis_path': str(analysis_path), 'final_analysis_sha256': sha_file(analysis_path),
              'manifest_sha256': frozen.MANIFEST, 'manifest_file_sha256': sha_file(prior / 'manifest.json'),
              'prior_run': str(prior), 'resume_run': str(resume),
              'prior_interruption_record_sha256': sha_file(prior / INTERRUPTION),
              'resume_plan_sha256': sha_file(resume / 'resume-plan.json'),
              'launch_receipt_sha256': sha_file(resume / 'launch-receipt.json'), 'owned_processes_stopped': stopped['owned_processes_stopped'],
              'prior_launch_receipt': 'Absent: the prior launcher was killed with WSL before cleanup; see the interruption record.',
              'cases': reports, 'pairs': pairs, 'registered_case_slots': 24,
              'outcome_counts_preserved': dict(Counter(c.get('official_analysis_outcome') for c in reports)),
              'new_statistical_tests': 0, 'new_model_generations': 0, 'new_env_resets': 0, 'new_env_steps': 0,
              'exposure_based_exclusions': 0,
              'limits': ['Each case is read from exactly one of the prior or resume run directories; every pair lies in one directory.',
                         'One zero-step interrupted case was re-executed in the resume run; it is flagged per case.',
                         *frozen_limits()]}
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('x', encoding='utf-8') as stream:
        json.dump(result, stream, indent=2, ensure_ascii=False, allow_nan=False)
    print(json.dumps({'status': result['status'], 'output': str(output), 'sha256': sha_file(output)}))
    return result


def frozen_limits():
    # The frozen audit embeds its limit statements inside main(); recover them verbatim.
    source = FROZEN.read_text(encoding='utf-8')
    start = source.index("'limits': [") + len("'limits': ")
    end = source.index("]}", start) + 1
    return frozen.ast.literal_eval(source[start:end])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prior', type=Path, required=True)
    parser.add_argument('--resume', type=Path, required=True)
    parser.add_argument('--analysis', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(argv)
    prior, resume, analysis, output = (p.resolve() for p in (args.prior, args.resume, args.analysis, args.output))
    require(prior.is_relative_to(ROOT / 'runs') and resume.is_relative_to(ROOT / 'runs')
            and analysis.is_relative_to(ROOT) and output.is_relative_to(ROOT / 'work'), 'Unexpected path scope')
    audit(prior, resume, analysis, output)


if __name__ == '__main__':
    main()
